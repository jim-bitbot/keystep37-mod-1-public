def get_sysex(param_id: int) -> bytes:
    return SESS + bytes([0x01, 0x00, 0x41, param_id & 0x7F, 0xF7])


def amidi_hex(msg: bytes) -> str:
    return " ".join(f"{b:02X}" for b in msg)
